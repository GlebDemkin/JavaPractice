package practice29;

public class A {
    {
        /*
         * Первый логический блок выполняется при создании объекта.
         * На этом этапе поле id ещё не получило значение 1,
         * поэтому используется значение по умолчанию для int — 0.
         */
        System.out.println("logic (1) id= " + this.id);
    }

    static {
        /*
         * Статический блок выполняется один раз:
         * при первом обращении к классу A.
         */
        System.out.println("static logic");
    }

    private int id = 1;

    public A(int id) {
        /*
         * Конструктор выполняется после всех логических блоков
         * и после инициализации полей.
         */
        this.id = id;
        System.out.println("ctor id= " + id);
    }

    {
        /*
         * Второй логический блок выполняется после инициализации поля id = 1,
         * потому что он расположен ниже объявления поля.
         */
        System.out.println("logic (2) id= " + id);
    }
}