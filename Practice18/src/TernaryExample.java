public class TernaryExample {
    public static void main(String[] args) {
        /*
         * Переменная a определяет, какое значение будет записано в i.
         * Если a равно 1, то i будет равно 1.
         * Если a равно 2, то i будет равно 2.
         * Во всех остальных случаях i будет равно 3.
         */
        int a = 2;

        /*
         * Тернарный оператор имеет вид:
         * условие ? значение_если_true : значение_если_false
         *
         * Здесь используется вложенный тернарный оператор:
         * если a == 1, возвращается 1;
         * иначе проверяется a == 2;
         * если a == 2, возвращается 2;
         * иначе возвращается 3.
         */
        int i = (a == 1) ? 1 : (a == 2) ? 2 : 3;

        System.out.println("a = " + a);
        System.out.println("i = " + i);
    }
}